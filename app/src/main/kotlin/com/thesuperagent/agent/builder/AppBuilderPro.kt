package com.thesuperagent.agent.builder

import com.thesuperagent.agent.core.LogStore
import com.thesuperagent.agent.core.SecurePrefs
import com.thesuperagent.agent.tools.DeviceControlHub
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONObject
import java.io.File
import java.net.HttpURLConnection
import java.net.URL
import java.util.Base64
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * App Builder Pro — generates Android Kotlin Compose + Web React + Node backend
 * from a natural-language prompt inside the sandbox workspace, zips and can push
 * to GitHub after auth (PAT stored encrypted).
 */
object AppBuilderPro {

    data class BuildLog(val line: String, val ok: Boolean)

    val logs = ArrayDeque<BuildLog>()

    private fun log(line: String, ok: Boolean = true) {
        synchronized(logs) {
            logs.addLast(BuildLog(line, ok))
            while (logs.size > 200) logs.removeFirst()
        }
    }

    fun slug(prompt: String): String =
        prompt.lowercase().replace(Regex("[^a-z0-9]+"), "-").trim('-').take(24).ifBlank { "my-app" }

    fun generate(prompt: String): String {
        val name = slug(prompt)
        val root = File(DeviceControlHub.workspace(), name)
        log("workspace: ${root.path}")
        root.mkdirs()

        // Android Kotlin Compose
        val androidDir = File(root, "android").apply { mkdirs() }
        File(androidDir, "MainActivity.kt").writeText(mainActivityKt(name, prompt))
        File(androidDir, "build.gradle.kts").writeText(appGradle(name))

        // Web React
        val webDir = File(root, "web").apply { mkdirs() }
        File(webDir, "App.jsx").writeText(reactApp(name, prompt))
        File(webDir, "package.json").writeText("""{"name":"$name-web","version":"1.0.0","dependencies":{"react":"^18.2.0","react-dom":"^18.2.0"}}""")

        // Node backend
        val apiDir = File(root, "api").apply { mkdirs() }
        File(apiDir, "server.js").writeText(nodeServer(name))
        File(apiDir, "package.json").writeText("""{"name":"$name-api","version":"1.0.0","dependencies":{"express":"^4.18.2"}}""")

        File(root, "README.md").writeText(
            "# $name\n\nGenerated by The Super Agent from prompt:\n> $prompt\n\n" +
            "- android/ — Kotlin Compose app skeleton\n- web/ — React front-end\n- api/ — Node/Express backend\n")

        log("generated: android/, web/, api/, README.md")
        return name
    }

    fun zipProject(name: String): File? {
        val root = File(DeviceControlHub.workspace(), name)
        if (!root.exists()) return null
        val out = File(DeviceControlHub.workspace(), "$name.zip")
        val ok = runCatching {
            ZipOutputStream(out.outputStream()).use { z ->
                root.walkTopDown().filter { it.isFile }.forEach { f ->
                    z.putNextEntry(ZipEntry(f.relativeTo(root).path))
                    f.inputStream().use { it.copyTo(z) }
                    z.closeEntry()
                }
            }
            log("zip ready: ${out.name} (${out.length()} bytes)")
            true
        }.getOrElse {
            log("zip failed: ${it.message}", false)
            false
        }
        return if (ok) out else null
    }

    /** Auto-fix suggestions based on prompt analysis. */
    fun suggestions(prompt: String): List<String> {
        val s = mutableListOf<String>()
        if (!prompt.contains("offline", true)) s.add("Add offline cache (Room) for resilience")
        if (!prompt.contains("permission", true)) s.add("Declare runtime permissions before use")
        if (prompt.contains("login", true) || prompt.contains("auth", true))
            s.add("Store tokens in EncryptedSharedPreferences, never in plain prefs")
        if (prompt.contains("list", true)) s.add("Use LazyColumn for large lists")
        return s
    }

    /* ---------- GitHub push via Contents API (PAT auth) ---------- */
    suspend fun pushToGitHub(project: String): String = withContext(Dispatchers.IO) {
        val token = SecurePrefs.githubToken
        val repo = SecurePrefs.githubRepo
        if (token.isBlank() || repo.isBlank())
            return@withContext "GitHub: Settings mein token + owner/repo set karo."
        val root = File(DeviceControlHub.workspace(), project)
        if (!root.exists()) return@withContext "Project not found: $project"
        var ok = 0; var fail = 0
        root.walkTopDown().filter { it.isFile }.forEach { f ->
            val path = f.relativeTo(root).path
            val b64 = Base64.getEncoder().encodeToString(f.readBytes())
            val body = JSONObject()
                .put("message", "Super Agent: add $path")
                .put("content", b64)
            try {
                val conn = URL("https://api.github.com/repos/$repo/contents/$project/$path")
                    .openConnection() as HttpURLConnection
                conn.requestMethod = "PUT"
                conn.doOutput = true
                conn.setRequestProperty("Authorization", "Bearer $token")
                conn.setRequestProperty("Content-Type", "application/json")
                conn.setRequestProperty("User-Agent", "The-Super-Agent")
                conn.outputStream.use { it.write(body.toString().toByteArray()) }
                if (conn.responseCode in 200..299) ok++ else fail++
                conn.disconnect()
            } catch (t: Throwable) { fail++ }
        }
        LogStore.log("github", "pushed $ok files, $fail failed")
        "GitHub push: $ok files OK, $fail failed."
    }

    /* ---------- templates ---------- */
    private fun mainActivityKt(name: String, prompt: String) = """
package com.example.$name

import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.foundation.layout.*

// Generated by The Super Agent — prompt: $prompt
class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            MaterialTheme {
                Surface(Modifier.fillMaxSize()) {
                    var text by remember { mutableStateOf("Hello from $name") }
                    Column(Modifier.padding(16.dp)) {
                        Text(text, style = MaterialTheme.typography.headlineSmall)
                        Spacer(Modifier.height(8.dp))
                        Text("Prompt: $prompt")
                    }
                }
            }
        }
    }
}
""".trimIndent()

    private fun appGradle(name: String) = """
