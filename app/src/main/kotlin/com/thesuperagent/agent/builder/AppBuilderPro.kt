    id("com.android.application")
    id("org.jetbrains.kotlin.android")
}
android {
    namespace = "com.example.$name"
    compileSdk = 34
    defaultConfig {
        applicationId = "com.example.$name"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0"
    }
    buildFeatures { compose = true }
}
dependencies {
    implementation(platform("androidx.compose:compose-bom:2024.02.00"))
    implementation("androidx.activity:activity-compose:1.8.2")
    implementation("androidx.compose.material3:material3")
}
""".trimIndent()

    private fun reactApp(name: String, prompt: String) = """
import React, { useState } from "react";
// Generated by The Super Agent — prompt: $prompt
export default function App() {
  const [msg, setMsg] = useState("Hello from $name web");
  return (
    <main style={{ fontFamily: "system-ui", padding: 24, background: "#050A14", color: "#00E5FF", minHeight: "100vh" }}>
      <h1>{msg}</h1>
      <p>Prompt: $prompt</p>
      <button onClick={() => setMsg("Clicked!")}>Tap</button>
    </main>
  );
}
""".trimIndent()

    private fun nodeServer(name: String) = """
// Generated by The Super Agent — $name backend
const express = require("express");
const app = express();
app.use(express.json());
app.get("/", (req, res) => res.json({ app: "$name", status: "ok" }));
app.post("/echo", (req, res) => res.json({ echo: req.body }));
const PORT = process.env.PORT || 3000;
app.listen(PORT, () => console.log("$name api on", PORT));
""".trimIndent()
}
